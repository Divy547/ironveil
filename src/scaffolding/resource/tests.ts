// Two distinct, valid example values per type, so an update visibly changes
// something. They are TypeScript source text.
const SAMPLES: Record<FieldType, (name: string) => string> = {
  string: (name) => `'Example ${name}'`,
  text: (name) => `'Example ${name}'`,
  int: () => '1',
  float: () => '1.5',
  decimal: () => '9.99',
  boolean: () => 'true',
  datetime: () => "'2026-01-01T00:00:00.000Z'",
};

const UPDATED_SAMPLES: Record<FieldType, (name: string) => string> = {
  string: (name) => `'Updated ${name}'`,
  text: (name) => `'Updated ${name}'`,
  int: () => '2',
  float: () => '2.5',
  decimal: () => '19.99',
  boolean: () => 'false',
  datetime: () => "'2027-01-01T00:00:00.000Z'",
};

function sample(field: FieldSpec): string {
  return SAMPLES[field.type](field.name);
}

function objectLiteral(entries: ReadonlyArray<readonly [string, string]>, indent: string): string {
  if (entries.length === 0) {
    return '{}';
  }
  return [
    '{',
    ...entries.map(([key, value]) => `${indent}  ${key}: ${value},`),
    `${indent}}`,
  ].join('\n');
}

/** Unit tests for the service, with PrismaService mocked. */
export function buildServiceSpec(
  names: ResourceNames,
  fields: readonly FieldSpec[],
): string {
  const { pascal, camel, kebab, pluralKebab, pluralPascal } = names;
  const payload = objectLiteral(
    fields.map((field) => [field.name, sample(field)] as const),
    '    ',
  );
  const first = fields[0];
  const patch = objectLiteral(
    first === undefined ? [] : [[first.name, UPDATED_SAMPLES[first.type](first.name)]],
    '    ',
  );

  return file([
    "import { NotFoundException } from '@nestjs/common';",
    "import { Test } from '@nestjs/testing';",
    "import { PrismaService } from '../../infrastructure/prisma/prisma.service';",
    `import { Create${pascal}Dto } from './dto/create-${kebab}.dto';`,
    `import { Update${pascal}Dto } from './dto/update-${kebab}.dto';`,
    `import { ${pluralPascal}Service } from './${pluralKebab}.service';`,
    '',
    `describe('${pluralPascal}Service', () => {`,
    `  let service: ${pluralPascal}Service;`,
    '',
    '  const delegate = {',
    '    create: jest.fn(),',
    '    findMany: jest.fn(),',
    '    findUnique: jest.fn(),',
    '    update: jest.fn(),',
    '    delete: jest.fn(),',
    '    count: jest.fn(),',
    '  };',
    '  const prisma = {',
    `    ${camel}: delegate,`,
    '    $transaction: jest.fn((operations: unknown[]) => Promise.all(operations)),',
    '  };',
    '',
    '  beforeEach(async () => {',
    '    jest.clearAllMocks();',
    '',
    '    const moduleRef = await Test.createTestingModule({',
    `      providers: [${pluralPascal}Service, { provide: PrismaService, useValue: prisma }],`,
    '    }).compile();',
    '',
    `    service = moduleRef.get(${pluralPascal}Service);`,
    '  });',
    '',
    "  it('creates a record from the DTO', async () => {",
    `    const dto: Create${pascal}Dto = ${payload};`,
    "    delegate.create.mockResolvedValue({ id: 'id-1', ...dto });",
    '',
    '    const result = await service.create(dto);',
    '',
    '    expect(delegate.create).toHaveBeenCalledWith({ data: dto });',
    "    expect(result).toMatchObject({ id: 'id-1' });",
    '  });',
    '',
    "  it('lists one page and reports the totals', async () => {",
    "    delegate.findMany.mockResolvedValue([{ id: 'id-3' }]);",
    '    delegate.count.mockResolvedValue(45);',
    '',
    '    const result = await service.findAll({ page: 3, limit: 20 });',
    '',
    '    expect(delegate.findMany).toHaveBeenCalledWith({',
    '      skip: 40,',
    '      take: 20,',
    "      orderBy: { createdAt: 'desc' },",
    '    });',
    '    expect(result).toEqual({',
    "      data: [{ id: 'id-3' }],",
    '      meta: { total: 45, page: 3, limit: 20, totalPages: 3 },',
    '    });',
    '  });',
    '',
    "  it('returns a record by id', async () => {",
    "    delegate.findUnique.mockResolvedValue({ id: 'id-1' });",
    '',
    "    await expect(service.findOne('id-1')).resolves.toEqual({ id: 'id-1' });",
    "    expect(delegate.findUnique).toHaveBeenCalledWith({ where: { id: 'id-1' } });",
    '  });',
    '',
    "  it('throws NotFoundException when the record does not exist', async () => {",
    '    delegate.findUnique.mockResolvedValue(null);',
    '',
    "    await expect(service.findOne('missing')).rejects.toBeInstanceOf(",
    '      NotFoundException,',
    '    );',
    '  });',
    '',
    "  it('updates a record', async () => {",
    `    const dto: Update${pascal}Dto = ${patch};`,
    "    delegate.update.mockResolvedValue({ id: 'id-1', ...dto });",
    '',
    "    await service.update('id-1', dto);",
    '',
    '    expect(delegate.update).toHaveBeenCalledWith({',
    "      where: { id: 'id-1' },",
    '      data: dto,',
    '    });',
    '  });',
    '',
    "  it('deletes a record', async () => {",
    "    delegate.delete.mockResolvedValue({ id: 'id-1' });",
    '',
    "    await service.remove('id-1');",
    '',
    "    expect(delegate.delete).toHaveBeenCalledWith({ where: { id: 'id-1' } });",
    '  });',
    '});',
  ]);
}

/**
 * HTTP-level test against the real AppModule (validation pipe, exception
 * filter, routing, and the JWT guard when auth is on) with the Prisma model
 * replaced by a small in-memory fake, so it needs no database.
 */
export function buildE2eSpec(
  names: ResourceNames,
  fields: readonly FieldSpec[],
  config: IronveilConfig,
): string {
  const { camel, pluralKebab } = names;
  const route = `/${pluralKebab}`;
  const jwt = config.auth === 'jwt';

  // Reuse the project's own test environment setup (DATABASE_URL, JWT_SECRET, ...).
  const testEnv = createTemplateRenderer().render('{{testingTestEnv}}', config);

  // `payload` sits at describe level (2 spaces), `patch` inside an `it` (4).
  const payload = objectLiteral(
    fields.map((field) => [field.name, sample(field)] as const),
    '  ',
  );
  const first = fields[0];
  const patch = objectLiteral(
    first === undefined ? [] : [[first.name, UPDATED_SAMPLES[first.type](first.name)]],
    '    ',
  );
  const hasRequired = fields.some((field) => !field.optional);

  return file([
    testEnv,
    '',
    "import { INestApplication, ValidationPipe } from '@nestjs/common';",
    ...(jwt ? ["import { JwtService } from '@nestjs/jwt';"] : []),
    "import { Test } from '@nestjs/testing';",
    "import * as request from 'supertest';",
    "import { PrismaService } from '../src/infrastructure/prisma/prisma.service';",
    ...(config.redis
      ? ["import { RedisService } from '../src/infrastructure/redis/redis.service';"]
      : []),
    '',
    'type Row = { id: string } & Record<string, unknown>;',
    '',
    '// An in-memory stand-in for the Prisma delegate. Like the real client, a',
    '// missing row makes update/delete fail with a P2025 error.',
    'function createFakeDelegate() {',
    '  const rows = new Map<string, Row>();',
    '  let sequence = 0;',
    '',
    '  const notFound = () =>',
    "    Object.assign(new Error('Record not found'), {",
    "      name: 'PrismaClientKnownRequestError',",
    "      code: 'P2025',",
    '    });',
    '',
    '  return {',
    '    create: ({ data }: { data: Record<string, unknown> }) => {',
    '      const now = new Date();',
    '      sequence += 1;',
    '      const row: Row = { id: `id-${sequence}`, ...data, createdAt: now, updatedAt: now };',
    '      rows.set(row.id, row);',
    '      return Promise.resolve(row);',
    '    },',
    '    findMany: ({ skip = 0, take }: { skip?: number; take: number }) =>',
    '      Promise.resolve([...rows.values()].slice(skip, skip + take)),',
    '    count: () => Promise.resolve(rows.size),',
    '    findUnique: ({ where }: { where: { id: string } }) =>',
    '      Promise.resolve(rows.get(where.id) ?? null),',
    '    update: ({ where, data }: { where: { id: string }; data: Record<string, unknown> }) => {',
    '      const row = rows.get(where.id);',
    '      if (row === undefined) {',
    '        return Promise.reject(notFound());',
    '      }',
    '      const updated: Row = { ...row, ...data, updatedAt: new Date() };',
    '      rows.set(updated.id, updated);',
    '      return Promise.resolve(updated);',
    '    },',
    '    delete: ({ where }: { where: { id: string } }) => {',
    '      const row = rows.get(where.id);',
    '      if (row === undefined) {',
    '        return Promise.reject(notFound());',
    '      }',
    '      rows.delete(where.id);',
    '      return Promise.resolve(row);',
    '    },',
    '  };',
    '}',
    '',
    `describe('${names.pluralPascal} (e2e)', () => {`,
    '  let app: INestApplication;',
    '  let authorize: (test: request.Test) => request.Test;',
    '',
    '  beforeEach(async () => {',
    "    const { AppModule } = await import('../src/app.module');",
    '',
    '    const moduleRef = await Test.createTestingModule({',
    '      imports: [AppModule],',
    '    })',
    '      .overrideProvider(PrismaService)',
    '      .useValue({',
    '        onModuleInit: jest.fn(),',
    '        onModuleDestroy: jest.fn(),',
    '        $connect: jest.fn(),',
    '        $disconnect: jest.fn(),',
    '        $queryRaw: jest.fn().mockResolvedValue([{ ok: 1 }]),',
    '        $transaction: (operations: Array<Promise<unknown>>) =>',
    '          Promise.all(operations),',
    `        ${camel}: createFakeDelegate(),`,
    '      })',
    ...(config.redis
      ? [
          '      .overrideProvider(RedisService)',
          '      .useValue({',
          '        onModuleInit: jest.fn(),',
          '        onModuleDestroy: jest.fn(),',
          '        connect: jest.fn(),',
          '        quit: jest.fn(),',
          "        ping: jest.fn().mockResolvedValue('PONG'),",
          '      })',
        ]
      : []),
    '      .compile();',
    '',
    '    app = moduleRef.createNestApplication();',
    '    // main.ts configures validation, not AppModule, so mirror it here.',
    '    app.useGlobalPipes(',
    '      new ValidationPipe({',
    '        whitelist: true,',
    '        forbidNonWhitelisted: true,',
    '        transform: true,',
    '      }),',
    '    );',
    '    await app.init();',
    '',
    ...(jwt
      ? [
          '    const token = app.get(JwtService, { strict: false }).sign({',
          "      sub: 'user-1',",
          "      email: 'user@example.com',",
          "      role: 'USER',",
          '    });',
          "    authorize = (test) => test.set('Authorization', `Bearer ${token}`);",
        ]
      : ['    authorize = (test) => test;']),
    '  });',
    '',
    '  afterEach(async () => {',
    '    await app.close();',
    '  });',
    '',
    '  const server = () => app.getHttpServer();',
    `  const payload = ${payload};`,
    '',
    ...(jwt
      ? [
          "  it('rejects requests without a token', async () => {",
          `    await request(server()).get('${route}').expect(401);`,
          `    await request(server()).post('${route}').send(payload).expect(401);`,
          '  });',
          '',
        ]
      : []),
    "  it('creates a record', async () => {",
    '    const response = await authorize(',
    `      request(server()).post('${route}').send(payload),`,
    '    ).expect(201);',
    '',
    '    expect(response.body).toMatchObject(payload);',
    '    expect(response.body.id).toEqual(expect.any(String));',
    '  });',
    '',
    "  it('rejects unknown properties', async () => {",
    '    await authorize(',
    `      request(server()).post('${route}').send({ ...payload, unexpected: true }),`,
    '    ).expect(400);',
    '  });',
    '',
    ...(hasRequired
      ? [
          "  it('rejects a body that is missing required fields', async () => {",
          `    await authorize(request(server()).post('${route}').send({})).expect(400);`,
          '  });',
          '',
        ]
      : []),
    "  it('lists records page by page', async () => {",
    '    for (let index = 0; index < 3; index += 1) {',
    `      await authorize(request(server()).post('${route}').send(payload)).expect(201);`,
    '    }',
    '',
    '    const response = await authorize(',
    `      request(server()).get('${route}?page=2&limit=2'),`,
    '    ).expect(200);',
    '',
    '    expect(response.body.data).toHaveLength(1);',
    '    expect(response.body.meta).toEqual({',
    '      total: 3,',
    '      page: 2,',
    '      limit: 2,',
    '      totalPages: 2,',
    '    });',
    '  });',
    '',
    "  it('rejects an out-of-range page size', async () => {",
    `    await authorize(request(server()).get('${route}?limit=1000')).expect(400);`,
    '  });',
    '',
    "  it('gets a record by id and returns 404 for an unknown id', async () => {",
    '    const created = await authorize(',
    `      request(server()).post('${route}').send(payload),`,
    '    ).expect(201);',
    '',
    '    await authorize(',
    `      request(server()).get(\`${route}/\${created.body.id}\`),`,
    '    ).expect(200);',
    '',
    '    const missing = await authorize(',
    `      request(server()).get('${route}/does-not-exist'),`,
    '    ).expect(404);',
    '    expect(missing.body.statusCode).toBe(404);',
    '  });',
    '',
    "  it('updates a record, and returns 404 when it does not exist', async () => {",
    '    const created = await authorize(',
    `      request(server()).post('${route}').send(payload),`,
    '    ).expect(201);',
    `    const patch = ${patch};`,
    '',
    '    const updated = await authorize(',
    `      request(server()).patch(\`${route}/\${created.body.id}\`).send(patch),`,
    '    ).expect(200);',
    '    expect(updated.body).toMatchObject(patch);',
    '',
    '    await authorize(',
    `      request(server()).patch('${route}/does-not-exist').send(patch),`,
    '    ).expect(404);',
    '  });',
    '',
    "  it('deletes a record', async () => {",
    '    const created = await authorize(',
    `      request(server()).post('${route}').send(payload),`,
    '    ).expect(201);',
    '',
    '    await authorize(',
    `      request(server()).delete(\`${route}/\${created.body.id}\`),`,
    '    ).expect(204);',
    '    await authorize(',
    `      request(server()).get(\`${route}/\${created.body.id}\`),`,
    '    ).expect(404);',
    '  });',
    '});',
  ]);
}
