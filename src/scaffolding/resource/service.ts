import type { ResourceNames } from '../names.js';
import { file } from './code.js';

export function buildService(names: ResourceNames): string {
  const { pascal, camel, kebab, pluralPascal } = names;

  return file([
    "import { Injectable, NotFoundException } from '@nestjs/common';",
    "import { paginate } from '../../common/pagination/paginated';",
    "import { PaginationQueryDto } from '../../common/pagination/pagination-query.dto';",
    "import { PrismaService } from '../../infrastructure/prisma/prisma.service';",
    `import { Create${pascal}Dto } from './dto/create-${kebab}.dto';`,
    `import { Update${pascal}Dto } from './dto/update-${kebab}.dto';`,
    '',
    '@Injectable()',
    `export class ${pluralPascal}Service {`,
    '  constructor(private readonly prisma: PrismaService) {}',
    '',
    `  create(dto: Create${pascal}Dto) {`,
    `    return this.prisma.${camel}.create({ data: dto });`,
    '  }',
    '',
    '  async findAll(query: PaginationQueryDto) {',
    '    const [data, total] = await this.prisma.$transaction([',
    `      this.prisma.${camel}.findMany({`,
    '        skip: (query.page - 1) * query.limit,',
    '        take: query.limit,',
    "        orderBy: { createdAt: 'desc' },",
    '      }),',
    `      this.prisma.${camel}.count(),`,
    '    ]);',
    '',
    '    return paginate(data, total, query);',
    '  }',
    '',
    '  async findOne(id: string) {',
    `    const ${camel} = await this.prisma.${camel}.findUnique({`,
    '      where: { id },',
    '    });',
    '',
    `    if (!${camel}) {`,
    `      throw new NotFoundException(\`${pascal} \${id} not found\`);`,
    '    }',
    '',
    `    return ${camel};`,
    '  }',
    '',
    `  update(id: string, dto: Update${pascal}Dto) {`,
    '    // A missing row makes Prisma throw P2025, which the global exception',
    '    // filter already turns into a 404.',
    `    return this.prisma.${camel}.update({ where: { id }, data: dto });`,
    '  }',
    '',
    '  async remove(id: string): Promise<void> {',
    `    await this.prisma.${camel}.delete({ where: { id } });`,
    '  }',
    '}',
  ]);
}
